function line(who, key, arg) {
  const set = LINES[who] && LINES[who][key];
  if (!set) return '';
  if (typeof set === 'function') return pick(set(arg));
  if (Array.isArray(set)) return pick(set);
  if (typeof set === 'object') return set[arg] || '';
  return set;
}
